import { createHash, randomBytes } from "node:crypto";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dirname, "../..");
const harness = "scripts/qualification/csprng/external-battery-harness.mjs";
const qualifiedSource = "services/game-engine/src/GameEngine.Application/Services/CertifiedCsprngRuntimeServices.cs";
const expectedHash = "53ecf20c1690b3e240f00d8df611b7bc57f413aba6434236ed72eb4ac9b74d30";
const qaRoot = `.qa/csprng-1.3b/qa-${Date.now()}-${randomBytes(4).toString("hex")}`;
const firstId = `qa-sample-a-${randomBytes(6).toString("hex")}`;
const secondId = `qa-sample-b-${randomBytes(6).toString("hex")}`;

assert(sha256(readFileSync(join(root, qualifiedSource))) === expectedHash, "Qualified implementation hash changed.");
const dockerfile = read("scripts/qualification/csprng/external-batteries/Dockerfile");
const harnessSource = read(harness);
assert(dockerfile.includes("ARG PRACTRAND_VERSION=0.96") && dockerfile.includes("sourceforge.net/projects/pracrand"), "PractRand source is not pinned.");
assert(dockerfile.includes("dieharder=${DIEHARDER_VERSION}"), "dieharder package version is not pinned.");
assert(dockerfile.includes("sts-2_1_2.zip"), "NIST STS source is not pinned.");
assert(dockerfile.includes("COMPILER_VERSION"), "Qualification image must preserve its build compiler identity.");
assert(!dockerfile.match(/FROM\s+[^\n]*:latest/i), "Qualification image must not use latest tags.");
assert(harnessSource.includes("createReadStream") && !harnessSource.includes("sha256(readFileSync(samplePath))"), "Sample verification must stream files larger than Node's 2 GiB buffer limit.");

run("node", [harness, "build"]);
run("node", [harness, "generate", "--sample-id", firstId, "--bytes", "1048576", "--output-root", qaRoot]);
run("node", [harness, "generate", "--sample-id", secondId, "--bytes", "1048576", "--output-root", qaRoot]);

const first = join(root, qaRoot, firstId);
const second = join(root, qaRoot, secondId);
const firstManifest = JSON.parse(readFileSync(join(first, "manifest.json"), "utf8"));
const secondManifest = JSON.parse(readFileSync(join(second, "manifest.json"), "utf8"));
assert(firstManifest.manifestPayload.sampleId !== secondManifest.manifestPayload.sampleId, "Independent sample IDs collided.");
assert(firstManifest.manifestPayload.publicInitialization.personalizationSha256 !== secondManifest.manifestPayload.publicInitialization.personalizationSha256, "Independent initialization evidence collided.");
assert(firstManifest.manifestPayload.publicInitialization.generateRequestMaximumBytes === 65536, "Generate chunk limit is not recorded.");
assert(firstManifest.manifestPayload.publicInitialization.generateRequestCount === 16, "Generate request count is incorrect.");
assert(firstManifest.manifestPayload.publicInitialization.finalGenerateRequestBytes === 65536, "Final Generate chunk size is incorrect.");
assert(statSync(join(first, "sample.bin")).size === 1048576, "Generated byte count is incorrect.");
run("node", [harness, "verify", "--sample", first]);

const duplicate = spawnSync(
  "node",
  [harness, "generate", "--sample-id", firstId, "--bytes", "1048576", "--output-root", qaRoot],
  { cwd: root, encoding: "utf8" },
);
assert(duplicate.status !== 0, "Existing sample identity was silently overwritten.");
assert(
  JSON.parse(readFileSync(join(first, "manifest.json"), "utf8")).manifestPayload.rawSampleSha256 ===
    firstManifest.manifestPayload.rawSampleSha256,
  "Duplicate generation mutated existing evidence.",
);

run("node", [harness, "smoke", "--sample", first]);
const runsDirectory = join(first, "runs");
const runId = readdirSync(runsDirectory).at(-1);
assert(runId, "Smoke run evidence was not created.");
const runDirectory = join(runsDirectory, runId);
const execution = JSON.parse(readFileSync(join(runDirectory, "execution.json"), "utf8"));
assert(execution.executionPayload.classification === "NON_QUALIFICATION_SMOKE_TEST", "Smoke evidence classification is missing.");
assert(execution.executionPayload.status === "COMPLETED", "Smoke run was not completed.");
for (const tool of ["inventory", "practrand", "dieharder", "nist-sts"]) {
  assert(existsSync(join(runDirectory, `${tool}.stdout.log`)), `${tool} stdout was not preserved.`);
  assert(existsSync(join(runDirectory, `${tool}.stderr.log`)), `${tool} stderr was not preserved.`);
  assert(execution.executionPayload.results.some((result) => result.tool === tool && result.acceptedInput), `${tool} did not accept the sample.`);
}
assert(existsSync(join(runDirectory, "nist-sts-output.tar.gz")), "NIST STS detailed output was not preserved.");
assert(
  readFileSync(join(runDirectory, "inventory.stdout.log"), "utf8").includes("build_compiler="),
  "Qualification inventory did not capture the build compiler identity.",
);

const productionProjects = [
  "services/game-engine/src/GameEngine.Api/GameEngine.Api.csproj",
  "services/game-engine/src/GameEngine.Application/GameEngine.Application.csproj",
  "services/game-engine/src/GameEngine.Infrastructure/GameEngine.Infrastructure.csproj",
];
for (const project of productionProjects) {
  const source = read(project);
  assert(!/PractRand|dieharder|TestU01|NIST.STS/i.test(source), `${project} gained an external battery dependency.`);
}

console.log(`[csprng-external-battery-harness] PASS evidence=${join(root, qaRoot)}`);

function run(file, args) {
  const result = spawnSync(file, args, { cwd: root, encoding: "utf8", maxBuffer: 128 * 1024 * 1024 });
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  if (result.status !== 0) throw new Error(`${file} ${args.join(" ")} failed with status ${result.status}.`);
}

function read(path) {
  return readFileSync(join(root, path), "utf8");
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}
